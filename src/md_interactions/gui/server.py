# entry point
# --------------------------------------------------------------------------- #
def _refuse_if_port_busy(port: int) -> None:
    """Fail loudly when another instance is already answering on ``port``."""
    import socket

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
        probe.settimeout(0.4)
        if probe.connect_ex(("127.0.0.1", port)) == 0:
            raise MDInteractionsError(
                f"Port {port} is already serving: another `md-analyzer gui` is "
                "running. Close it, or start this one with --port <other>."
            )


def serve(topology, trajectory=None, port: int = 8765, stride: int = 1,
          open_browser: bool = True, results_dir="results_gui") -> None:
    """Start the local server (blocking) and optionally open the browser."""
    state = GuiState(topology=Path(topology),
                     trajectory=[Path(p) for p in (trajectory or [])],
                     stride=stride, results_dir=Path(results_dir).resolve())
    if not state.topology.is_file():
        raise MDInteractionsError(f"Topology not found: {state.topology}")

    # On Windows SO_REUSEADDR lets a second server bind the same port silently,
    # so requests would keep being answered by the older (stale) process.
    _refuse_if_port_busy(port)

    handler = type("_BoundHandler", (_Handler,), {"state": state})
    server = ThreadingHTTPServer(("127.0.0.1", port), handler)
    url = f"http://localhost:{port}"
    print(f"[md_interactions] GUI at {url}")
    print("[md_interactions] Ctrl-C to quit")
    if open_browser:
        threading.Timer(0.6, lambda: webbrowser.open(url)).start()
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\n[md_interactions] closed")
    finally:
        server.server_close()
