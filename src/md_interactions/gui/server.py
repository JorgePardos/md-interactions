def _system_info(state: GuiState) -> dict:
    state.load()
    universe = state.universe
    protein = universe.select_atoms("protein")
    ligands = []
    water = {"WAT", "HOH", "SOL", "TIP3", "T3P"}
    protein_resnames = set(protein.residues.resnames)
    seen = set()
    for residue in universe.residues:
        name = str(residue.resname)
        if name in protein_resnames or name in water or name in seen:
            continue
        seen.add(name)
        ligands.append({"resname": name, "resid": int(residue.resid),
                        "n_atoms": int(residue.atoms.n_atoms)})
    n_frames = len(universe.trajectory) if state.trajectory else 0
    return {
        "topology": str(state.topology),
        "trajectory": [str(p) for p in state.trajectory],
        "n_atoms": int(universe.atoms.n_atoms),
        "n_residues": int(universe.residues.n_residues),
        "n_protein_residues": int(protein.residues.n_residues),
        "n_frames": n_frames,
        "ligands": ligands[:20],
        "stride": state.stride,
    }


def _explore(state: GuiState, body: dict) -> dict:
    from .. import explore as ex

    system = state.build_system()
    mode = body.get("mode", "contacts")
    region = body.get("region") or ex.DEFAULT_REGION

    if mode == "contacts":
        table = ex.find_contacts(
            system, region=region, cutoff=float(body.get("cutoff", 4.0)),
            waters=body.get("waters", "aggregate"),
            min_occupancy=float(body.get("min_occupancy", 5.0)), verbose=False,
        )
        return {"mode": mode, "rows": _records(table)}

    if mode == "changes":
        bonds = ex.detect_bond_changes(system, verbose=False)
        protons = ex.detect_proton_transfers(system, verbose=False)
        return {"mode": mode, "bonds": _records(bonds), "protons": _records(protons)}

    raise MDInteractionsError(f"Unknown explore mode '{mode}'.")


def _records(table) -> list[dict]:
    if table is None or getattr(table, "empty", True):
        return []
    clean = table.replace({np.nan: None})
    return json.loads(clean.to_json(orient="records"))


def _start_run(state: GuiState, body: dict) -> None:
    """Launch the analysis in a worker thread so the UI stays responsive."""
    if state.job["status"] == "running":
        raise MDInteractionsError("An analysis is already running.")
    state.job = {"status": "running", "message": "Preparing...", "result": None}

    def worker() -> None:
        try:
            state.job["message"] = "Running the analysis..."
            result = _run_analysis(state, body)
            state.job = {"status": "done", "message": "Done", "result": result}
        except Exception as exc:
            state.job = {"status": "error",
                         "message": f"{type(exc).__name__}: {exc}", "result": None}

    threading.Thread(target=worker, daemon=True).start()


def _run_analysis(state: GuiState, body: dict) -> dict:
    """Build a configuration from the interactions picked in the browser."""
    from ..config import Config
    from ..runner import run_analyses

    interactions = body.get("interactions", [])
    if not interactions:
        raise MDInteractionsError("No interactions selected.")

    results_dir = Path(body.get("output", "results_gui")).resolve()
    state.results_dir = results_dir

    selections: dict[str, str] = {}
    distances: list[dict] = []
    angles: list[dict] = []
    dihedrals: list[dict] = []

    for entry in interactions:
        aliases = []
        for atom in entry["atoms"]:
            alias = _alias(atom)
            selections[alias] = f"resid {atom['resid']} and name {atom['name']}"
            aliases.append(alias)
        record = {"name": entry.get("name") or f"obs_{len(distances) + 1}",
                  "atoms": aliases,
                  "label": " – ".join(f"{a['resname']}{a['resid']}:{a['name']}"
                                      for a in entry["atoms"])}
        if entry.get("threshold"):
            record["threshold"] = float(entry["threshold"])
        kind = entry.get("kind", "distance")
        if kind == "distance":
            distances.append(record)
        elif kind == "angle":
            record.pop("threshold", None)
            angles.append(record)
        elif kind == "dihedral":
            record.pop("threshold", None)
            dihedrals.append(record)

    analyses: dict = {}
    if distances:
        analyses["distances"] = {"enabled": True, "pairs": distances}
    if angles:
        analyses["angles"] = {"enabled": True, "definitions": angles}
    if dihedrals:
        analyses["dihedrals"] = {"enabled": True, "definitions": dihedrals}

    config = Config.from_dict({
        "system": {
            "topology": str(state.topology),
            "trajectory": [str(p) for p in state.trajectory],
            "frames": {"stride": int(body.get("stride", state.stride))},
            "time": {"dt": None, "unit": body.get("time_unit", "ps")},
        },
        "output": {"directory": str(results_dir), "formats": ["png", "pdf"],
                   "dpi": 200},
        "selections": selections,
        "analyses": analyses,
        "report": {"enabled": True, "formats": ["markdown", "html"]},
    })

    output = run_analyses(config, verbose=False, strict=False)
    plots = sorted(p.name for p in (results_dir / "plots").glob("*.png"))
    summary = _records(output.summary) if output.summary is not None else []
    return {
        "plots": plots,
        "summary": summary,
        "failures": [{"analysis": name, "message": message}
                     for name, message in output.failures],
        "directory": str(results_dir),
    }


def _alias(atom: dict) -> str:
    raw = f"{atom['resname']}{atom['resid']}_{atom['name']}"
    return "".join(c if (c.isalnum() or c == "_") else "_" for c in raw)


