# HTML
# --------------------------------------------------------------------------- #
def _build_html(output: "RunOutput") -> str:
    config = output.config
    parts: list[str] = [
        "<!DOCTYPE html>", "<html lang='en'>", "<head>",
        "<meta charset='utf-8'>",
        "<meta name='viewport' content='width=device-width, initial-scale=1'>",
        f"<title>{_html.escape(config.report.title)}</title>",
        f"<style>{_CSS}</style>", "</head>", "<body>",
        f"<h1>{_html.escape(config.report.title)}</h1>",
        f"<p class='meta'>Generated by md_interactions on "
        f"{_dt.datetime.now().strftime('%Y-%m-%d %H:%M')}</p>",
        "<ul class='meta'>",
    ]
    for line in _metadata_lines(output):
        parts.append("<li>" + _markdown_inline_to_html(line.lstrip("- ")) + "</li>")
    parts.append("</ul>")

    parts.append("<h2>Summary</h2>")
    parts.append(_table_html(format_summary(output.summary)))

    for result in output.results:
        parts.append(f"<h2>{_html.escape(result.title)}</h2>")
        for note in result.notes:
            parts.append(f"<div class='note'>{_html.escape(note)}</div>")
        if result.summary is not None and not result.summary.empty:
            parts.append(_table_html(format_summary(result.summary)))
        for name, table in result.tables.items():
            if _is_report_table(name, table):
                parts.append(f"<h3>{_html.escape(name)}</h3>")
                parts.append(_table_html(table.head(30)))
        if result.plots:
            parts.append("<div class='gallery'>")
            for plot in result.plots:
                relative = _html.escape(output.paths.relative(plot))
                parts.append(
                    f"<figure><img src='{relative}' alt='{_html.escape(plot.stem)}'>"
                    f"<figcaption>{_html.escape(plot.stem)}</figcaption></figure>"
                )
            parts.append("</div>")

    if output.failures:
        parts.append("<h2>Failed analyses</h2>")
        for name, message in output.failures:
            parts.append(
                f"<div class='note fail'><b>{_html.escape(name)}</b>: "
                f"{_html.escape(message.splitlines()[0])}</div>"
            )

    parts += ["</body>", "</html>"]
    return "\n".join(parts)


def _table_html(df: pd.DataFrame) -> str:
    if df is None or df.empty:
        return "<p><i>(no data)</i></p>"
    return df.to_html(index=False, border=0, float_format=lambda v: f"{v:.3f}",
                      na_rep="-")


def _markdown_inline_to_html(text: str) -> str:
    """Minimal ``**bold**`` / ``` `code` ``` conversion for the metadata list."""
    escaped = _html.escape(text)
    for marker, tag in (("**", "b"), ("`", "code")):
        pieces = escaped.split(marker)
        rebuilt = []
        for i, piece in enumerate(pieces):
            rebuilt.append(f"<{tag}>{piece}</{tag}>" if i % 2 else piece)
        escaped = "".join(rebuilt)
    return escaped
