import html as _html
from pathlib import Path
from typing import TYPE_CHECKING

import pandas as pd

from .io_utils import to_markdown_table

if TYPE_CHECKING:  # pragma: no cover
    from .runner import RunOutput

__all__ = ["write_report", "build_summary_markdown", "format_summary"]

_SUMMARY_COLUMNS = ["analysis", "observable", "unit", "n_frames",
                    "mean", "std", "min", "max"]

