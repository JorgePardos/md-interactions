def format_summary(summary: pd.DataFrame) -> pd.DataFrame:
    """Reorder/round the summary table for display."""
    if summary is None or summary.empty:
        return pd.DataFrame()
    columns = [c for c in _SUMMARY_COLUMNS if c in summary.columns]
    extras = [c for c in summary.columns if c not in columns]
    display = summary[columns + extras].copy()
    for column in display.columns:
        if pd.api.types.is_float_dtype(display[column]):
            display[column] = display[column].round(3)
    return display


def build_summary_markdown(output: "RunOutput") -> str:
    """Markdown version of the global summary table (mean ± std, min, max)."""
    display = format_summary(output.summary)
    if display.empty:
        return "_No quantitative results were produced._\n"

    compact = pd.DataFrame({
        "Analysis": display["analysis"],
        "Observable": display["observable"],
        "Mean ± SD": [f"{m:.3f} ± {s:.3f}" if pd.notna(s) else f"{m:.3f}"
                      for m, s in zip(display["mean"], display["std"])],
        "Min": display["min"],
        "Max": display["max"],
        "Unit": display["unit"],
        "Frames": display["n_frames"],
    })
    if "occupancy_pct" in display.columns:
        compact["Occupancy (%)"] = display["occupancy_pct"]
    if "frames_below_threshold_%" in display.columns:
        compact["< threshold (%)"] = display["frames_below_threshold_%"]
    return to_markdown_table(compact)


def write_report(output: "RunOutput") -> list[Path]:
    """Write ``summary/summary.md`` plus the requested report formats."""
    paths = output.paths
    files: list[Path] = []

    summary_md = build_summary_markdown(output)
    summary_path = paths.summary / "summary.md"
    summary_path.write_text(
        f"# Summary\n\n{summary_md}\n", encoding="utf-8"
    )
    files.append(summary_path)

    formats = output.config.report.formats
    markdown = _build_markdown(output, summary_md)
    if "markdown" in formats:
        path = paths.root / "report.md"
        path.write_text(markdown, encoding="utf-8")
        files.append(path)
    if "html" in formats:
        path = paths.root / "report.html"
        path.write_text(_build_html(output), encoding="utf-8")
        files.append(path)
    return files


# --------------------------------------------------------------------------- #
# Markdown
# --------------------------------------------------------------------------- #
def _build_markdown(output: "RunOutput", summary_md: str) -> str:
    config = output.config
    lines: list[str] = [f"# {config.report.title}", ""]
    lines += [f"_Generated by md_interactions on "
              f"{_dt.datetime.now().strftime('%Y-%m-%d %H:%M')}_", ""]
    lines += _metadata_lines(output)
    lines += ["", "## Summary", "", summary_md, ""]

    for result in output.results:
        lines.append(f"## {result.title}")
        lines.append("")
        for note in result.notes:
            lines.append(f"> {note}")
        if result.notes:
            lines.append("")
        if result.summary is not None and not result.summary.empty:
            lines.append(to_markdown_table(format_summary(result.summary)))
            lines.append("")
        for name, table in result.tables.items():
            if _is_report_table(name, table):
                lines.append(f"**{name}**")
                lines.append("")
                lines.append(to_markdown_table(table.head(30)))
                lines.append("")
        for plot in result.plots:
            relative = output.paths.relative(plot)
            lines.append(f"![{plot.stem}]({relative})")
            lines.append("")
        data_files = sorted({f"data/{name}.csv" for name in result.tables})
        if data_files:
            lines.append(f"_Data: {', '.join(data_files)}_")
            lines.append("")

    if output.failures:
        lines += ["## Failed analyses", ""]
        for name, message in output.failures:
            lines.append(f"- **{name}**: {message.splitlines()[0]}")
        lines.append("")
    return "\n".join(lines)


def _metadata_lines(output: "RunOutput") -> list[str]:
    config = output.config
    system = output.system
    if system is None:                      # data: mode, no trajectory involved
        dataset = output.dataset
        lines = [
            f"- **Data files**: `{', '.join(p.name for p in dataset.sources)}`",
            f"- **Rows analysed**: {dataset.n_frames}",
            f"- **Observables**: {', '.join(dataset.columns)}",
        ]
        if dataset.replica_labels is not None:
            counts = {name: int(mask.sum())
                      for name, mask in dataset.replica_masks().items()}
            listed = ", ".join(f"{k}: {v}" for k, v in counts.items())
            lines.append(f"- **Replicas**: {listed}")
        if config.source:
            lines.append(f"- **Configuration**: `{config.source.name}`")
        return lines

    trajectories = ", ".join(p.name for p in config.system.trajectory)
    lines = [
        f"- **Topology**: `{config.system.topology.name}`",
        f"- **Trajectory**: `{trajectories}`",
        f"- **Atoms**: {system.universe.atoms.n_atoms}",
        f"- **Frames analysed**: {system.n_frames} "
        f"(start={config.system.frames.start}, stop={config.system.frames.stop}, "
        f"stride={config.system.frames.stride})",
    ]
    if system.time_unit != "frame":
        lines.append(
            f"- **Time range**: {system.times[0]:g} – {system.times[-1]:g} "
            f"{system.time_unit} (dt = {system.dt_per_frame:g} {system.time_unit}/frame)"
        )
    if system.replica_labels is not None:
        counts = {name: int(mask.sum())
                  for name, mask in system.replica_masks().items()}
        listed = ", ".join(f"{k}: {v}" for k, v in counts.items())
        lines.append(f"- **Replicas**: {listed}")
    if config.source:
        lines.append(f"- **Configuration**: `{config.source.name}`")
    return lines


def _is_report_table(name: str, table: pd.DataFrame) -> bool:
    """Only small, human-readable tables are inlined in the report."""
    if name == "replica_overlap" and not table.empty:
        return True
    return name in {"hbonds_detected", "clusters"} and not table.empty


